import type { VocabularyEntry } from '@/types';

let n = 0;
const nextId = () => `vocab_${++n}`;

function entry(
  topic: string,
  french: string,
  english: string,
  example: string | undefined,
  tags: string[],
  gender: VocabularyEntry['gender'] = 'n/a',
): VocabularyEntry {
  const now = '2026-02-01T09:00:00.000Z';
  return {
    id: nextId(),
    type: 'vocabulary',
    title: `${french} — ${english}`,
    topic,
    french,
    english,
    example,
    gender,
    tags: [topic.toLowerCase(), ...tags],
    createdAt: now,
    updatedAt: now,
  };
}

